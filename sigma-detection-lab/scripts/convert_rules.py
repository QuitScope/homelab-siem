#!/usr/bin/env python3
"""Converts rules/ to Splunk SPL with the official pySigma Splunk backend and the HomeLab pipeline.

Writes generated/spl/<rule name>.spl (one query per rule, incl. correlation rules) and
generated/savedsearches.conf (alerts for level >= medium, plain saved searches below).
Uses the pySigma API instead of `sigma convert -od` because sigma-cli 3.1.0 leaves {index} empty for files
with a correlation (the second query overwrites the first) and drops the stanza of correlated base rules in
`-f savedsearches`.
"""
from pathlib import Path

from sigma.backends.splunk import SplunkBackend
from sigma.collection import SigmaCollection
from sigma.processing.pipeline import ProcessingPipeline
from sigma.rule import SigmaRule

ROOT = Path(__file__).resolve().parent.parent
PIPELINE = ROOT / "pipelines" / "splunk" / "homelab.yml"
HEADER = "# Generated by scripts/convert_rules.py from rules/ - do not edit, run scripts/convert-rules.sh\n"
# Sigma level -> Splunk alert severity (1 debug .. 6 fatal); levels below medium are not scheduled
SEVERITY = {"medium": 3, "high": 4, "critical": 5}
SCHEDULED_LEVELS = set(SEVERITY)


def convert_all() -> dict[str, str]:
    """Returns {relative output path: file content} for all rules."""
    backend = SplunkBackend(ProcessingPipeline.from_yaml(PIPELINE.read_text(encoding="utf-8")))
    rules = SigmaCollection.load_ruleset([str(ROOT / "rules")]).rules
    out, stanzas = {}, [HEADER]
    for rule in sorted(rules, key=lambda r: r.name):
        convert = backend.convert_rule if isinstance(rule, SigmaRule) else backend.convert_correlation_rule
        (query,) = convert(rule)  # exactly one query per rule, anything else is a bug
        out[f"generated/spl/{rule.name}.spl"] = query + "\n"
        search = " \\\n".join(query.splitlines())
        summary = " ".join(rule.description.split()).split(". ")[0].rstrip(".") + "."
        level = rule.level.name.lower()
        stanza = (f"\n[Sigma - {rule.title}]\n"
                  f"description = {summary} (Sigma id {rule.id}, level {level})\n"
                  f"search = {search}\n")
        if level in SCHEDULED_LEVELS:
            # Same cadence as the existing homelab alert: every 5 min over the last full 5 min,
            # listed under Activity > Triggered Alerts. Add email/webhook actions in Splunk if needed.
            stanza += ("enableSched = 1\ncron_schedule = */5 * * * *\n"
                       "dispatch.earliest_time = -5m@m\ndispatch.latest_time = @m\n"
                       "counttype = number of events\nrelation = greater than\nquantity = 0\n"
                       f"alert.track = 1\nalert.severity = {SEVERITY[level]}\nalert.digest_mode = 1\n")
        else:
            # Too noisy to alert on (e.g. every single failed login); available as a saved search
            stanza += "enableSched = 0\ndispatch.earliest_time = -24h\ndispatch.latest_time = now\n"
        stanzas.append(stanza)
    out["generated/savedsearches.conf"] = "".join(stanzas)
    return out


def main():
    spl_dir = ROOT / "generated" / "spl"
    for old in spl_dir.glob("*.spl"):
        old.unlink()
    spl_dir.mkdir(parents=True, exist_ok=True)
    for rel, content in convert_all().items():
        (ROOT / rel).write_text(content, encoding="utf-8", newline="\n")
        print("wrote", rel)


if __name__ == "__main__":
    main()
